TEST(DOVIDecoderConfigurationRecordTest, SelectLevelForSizeAndExactRate) {
  struct Case {
    uint32_t width, height, time_scale;
    int64_t duration;
    uint8_t expected_level;
  };
  const Case cases[] = {
      {512, 288, 10000000, 417083, 1},
      {1280, 720, 24000, 1001, 1},
      {1280, 720, 30, 1, 2},
      {1920, 1080, 24000, 1001, 3},
      {1920, 1080, 30, 1, 4},
      {1920, 1080, 60, 1, 5},
      {2560, 1440, 24, 1, 5},
      {3840, 2160, 10000000, 417083, 6},
      {3840, 2160, 10000000, 417084, 6},
      {3840, 2160, 24, 1, 6},
      {3840, 2160, 24001, 1000, 7},
      {3840, 2160, 30, 1, 7},
      {3840, 2160, 48, 1, 8},
      {3840, 2160, 60, 1, 9},
      {3840, 2160, std::numeric_limits<uint32_t>::max(),
       std::numeric_limits<int64_t>::max(), 6},
  };
  for (const auto& test : cases) {
    uint8_t level = 0;
    ASSERT_TRUE(DOVIDecoderConfigurationRecord::GetProfile5Level(
        test.width, test.height, test.time_scale, test.duration, &level));
    EXPECT_EQ(test.expected_level, level);
  }
}

TEST(DOVIDecoderConfigurationRecordTest, DoNotGuessUnsupportedLevel) {
  uint8_t level = 99;
  EXPECT_FALSE(DOVIDecoderConfigurationRecord::GetProfile5Level(
      3840, 2160, 61, 1, &level));
  EXPECT_EQ(0, level);
  EXPECT_FALSE(DOVIDecoderConfigurationRecord::GetProfile5Level(
      3841, 2160, 24, 1, &level));
  EXPECT_FALSE(DOVIDecoderConfigurationRecord::GetProfile5Level(
      3840, 2161, 24, 1, &level));
  EXPECT_FALSE(DOVIDecoderConfigurationRecord::GetProfile5Level(
      0, 2160, 24, 1, &level));
  EXPECT_FALSE(DOVIDecoderConfigurationRecord::GetProfile5Level(
      3840, 0, 24, 1, &level));
  EXPECT_FALSE(DOVIDecoderConfigurationRecord::GetProfile5Level(
      3840, 2160, 0, 1, &level));
  EXPECT_FALSE(DOVIDecoderConfigurationRecord::GetProfile5Level(
      3840, 2160, 24, 0, &level));
  EXPECT_FALSE(DOVIDecoderConfigurationRecord::GetProfile5Level(
      3840, 2160, 24, -1, &level));
  EXPECT_FALSE(DOVIDecoderConfigurationRecord::GetProfile5Level(
      3840, 2160, 24, 1, nullptr));
}

